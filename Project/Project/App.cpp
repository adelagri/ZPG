void App::KeyCallback(GLFWwindow* window, int key, int scancode, int action, int mods)
{
	App* app = static_cast<App*>(glfwGetWindowUserPointer(window));

	// scene switching
	// The following code was generated by AI (Source: Sonnet 5, Model: Claude Anthropic)
	if (action == GLFW_PRESS) {
		int newIndex = -1;
		if (key == GLFW_KEY_1) newIndex = 0;
		if (key == GLFW_KEY_2) newIndex = 1;
		if (key == GLFW_KEY_3) newIndex = 2;
		if (key == GLFW_KEY_4) newIndex = 3;

		if (newIndex >= 0 && newIndex < (int)app->scenes.size())
			app->currentSceneIndex = newIndex;
	}

	if (key == GLFW_KEY_ESCAPE && action == GLFW_PRESS)
		glfwSetWindowShouldClose(window, GL_TRUE);

	// rotation - continuous while key is pressed
	if (key == GLFW_KEY_A) {
		if (action == GLFW_PRESS) app->rotateLeftPressed = true;
		if (action == GLFW_RELEASE) app->rotateLeftPressed = false;
	}
	if (key == GLFW_KEY_D) {
		if (action == GLFW_PRESS) app->rotateRightPressed = true;
		if (action == GLFW_RELEASE) app->rotateRightPressed = false;
	}

	if (key == GLFW_KEY_TAB && action == GLFW_PRESS)
		app->scenes[app->currentSceneIndex]->SelectNextObject();

	// rotation axis selection
	if (key == GLFW_KEY_X && action == GLFW_PRESS) {
		DrawableObject* obj = app->scenes[app->currentSceneIndex]->GetSelectedObject();
		if (obj) obj->transform.rotationAxis = 0;
	}
	if (key == GLFW_KEY_Y && action == GLFW_PRESS) {
		DrawableObject* obj = app->scenes[app->currentSceneIndex]->GetSelectedObject();
		if (obj) obj->transform.rotationAxis = 1;
	}
	if (key == GLFW_KEY_Z && action == GLFW_PRESS) {
		DrawableObject* obj = app->scenes[app->currentSceneIndex]->GetSelectedObject();
		if (obj) obj->transform.rotationAxis = 2;
	}

	// translation
	if (key == GLFW_KEY_LEFT && action == GLFW_PRESS) {
		DrawableObject* obj = app->scenes[app->currentSceneIndex]->GetSelectedObject();
		if (obj) obj->transform.translation.x -= 0.1f;
	}
	if (key == GLFW_KEY_RIGHT && action == GLFW_PRESS) {
		DrawableObject* obj = app->scenes[app->currentSceneIndex]->GetSelectedObject();
		if (obj) obj->transform.translation.x += 0.1f;
	}
	// scale
	if (key == GLFW_KEY_UP && action == GLFW_PRESS) {
		DrawableObject* obj = app->scenes[app->currentSceneIndex]->GetSelectedObject();
		if (obj) obj->transform.scale += glm::vec3(0.1f);
	}
	if (key == GLFW_KEY_DOWN && action == GLFW_PRESS) {
		DrawableObject* obj = app->scenes[app->currentSceneIndex]->GetSelectedObject();
		if (obj) obj->transform.scale -= glm::vec3(0.1f);
	}
}

