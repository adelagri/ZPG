void App::Run()
{
	InitScenes();
	double lastFrameTime = glfwGetTime();

	while (!glfwWindowShouldClose(Window))
	{
		double currentTime = glfwGetTime();
		float deltaTime = static_cast<float>(currentTime - lastFrameTime);
		lastFrameTime = currentTime;

		Scene* currentScene = scenes[currentSceneIndex];

		float rotationSpeed = 1.5f; // radians per second

		// The following code was generated by AI (Source: Sonnet 5, Model: Claude Anthropic)
		if (rotateLeftPressed) {
			DrawableObject* obj = currentScene->GetSelectedObject();
			if (obj) obj->transform.angle += rotationSpeed * deltaTime;
		}
		if (rotateRightPressed) {
			DrawableObject* obj = currentScene->GetSelectedObject();
			if (obj) obj->transform.angle -= rotationSpeed * deltaTime;;
		}

		// Clear color and depth buffer
		glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);
		currentScene->Draw();

		// Display the rendered frame and process events
		glfwSwapBuffers(Window);
		glfwPollEvents();
	}
}

void App::InitScenes()
{
	Scene* scene1 = new Scene();
	ShaderProgram* shader1 = scene1->AddShader("shaders/basic.vert", "shaders/basic.frag");
	Model* model1 = scene1->AddModel(triangle, sizeof(triangle) / 6, 6);
	DrawableObject* object1 = new DrawableObject(model1, shader1);
	scene1->AddObject(object1);
	scenes.push_back(scene1);

	Scene* scene2 = new Scene();
	Model* model2 = scene2->AddModel(square, sizeof(square) / 6, 6);
	DrawableObject* object2 = new DrawableObject(model2, shader1);
	scene2->AddObject(object2);
	scenes.push_back(scene2);

	Scene* scene3 = new Scene();
	Model* model3 = scene3->AddModel(sphere, sizeof(sphere) / 6, 6);
	DrawableObject* object3 = new DrawableObject(model3, shader1);
	scene3->AddObject(object3);
	scenes.push_back(scene3);

	Scene* scene4 = new Scene();
	ShaderProgram* shader2 = scene4->AddShader("shaders/basic-forest.vert", "shaders/basic.frag");
	Model* model4 = scene4->AddModel(tree, sizeof(tree) / 6, 6);
	Model* model5 = scene4->AddModel(bushes, sizeof(bushes) / 6, 6);
	for (int i = 0; i < 13; i++) {
		DrawableObject* object4 = new DrawableObject(model4, shader2);

		// The following code was generated by AI (Source: Sonnet 5, Model: Claude Anthropic)
		// Randomize the position, scale, and rotation of the trees
		object4->transform.translation.x = (i - 6) * 1.5f + ((rand() % 100) / 100.0f - 0.5f);	// random offset in the range -0.5 to 0.5
		object4->transform.translation.y = 0.0f;
		object4->transform.translation.z = (rand() % 100) / 100.0f * 4.0f - 2.0f;	// random z position in the range -2.0 to 2.0

		float randomScale = 0.7f + (rand() % 100) / 100.0f * 0.6f; // range cca 0.7 - 1.3
		object4->transform.scale = glm::vec3(randomScale);

		object4->transform.angle = (rand() % 360) * (3.14159f / 180.0f); // random angle 0-360° in radians
		object4->transform.rotationAxis = 1; // rotation around Y (tree just rotates in place, doesn't fall over)

		scene4->AddObject(object4);
	}
	for (int i = 0; i < 12; i++) {
		DrawableObject* object5 = new DrawableObject(model5, shader2);

		// The following code was generated by AI (Source: Sonnet 5, Model: Claude Anthropic)
		object5->transform.translation.x = (i - 6) * 1.5f + ((rand() % 100) / 100.0f - 0.5f);	// random offset in the range -0.5 to 0.5
		object5->transform.translation.y = 0.0f;
		object5->transform.translation.z = (rand() % 100) / 100.0f * 4.0f - 2.0f;	// random z position in the range -2.0 to 2.0

		float randomScale = 0.7f + (rand() % 100) / 100.0f * 0.6f; // range cca 0.7 - 1.3
		object5->transform.scale = glm::vec3(randomScale);

		object5->transform.angle = (rand() % 360) * (3.14159f / 180.0f); // random angle 0-360° in radians
		object5->transform.rotationAxis = 1; // rotation around Y

		scene4->AddObject(object5);
	}

	scenes.push_back(scene4);
}

